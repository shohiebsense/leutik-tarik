package store

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"time"
)

// ProfilesDir is where profile blobs live. Overridable so the platform can run
// read-only in a container with a mounted volume.
func ProfilesDir() string {
	if d := os.Getenv("LEUTIK_PROFILES_DIR"); d != "" {
		return d
	}
	return "profiles-data"
}

// InsertProfile writes the blob and records its metadata.
//
// The file is written before the row: a row pointing at a missing blob would be
// a broken reference, while an orphan blob is only wasted space.
func (c *ClickHouse) InsertProfile(ctx context.Context, meta ProfileMeta, data []byte) error {
	dir := ProfilesDir()
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("profiles dir: %w", err)
	}
	// The id is generated by us, but it is still cleaned: it becomes a filename.
	safeID := filepath.Base(meta.ID)
	path := filepath.Join(dir, safeID+".pb.gz")
	if err := os.WriteFile(path, data, 0o640); err != nil {
		return fmt.Errorf("write profile: %w", err)
	}

	retention := uint32(meta.Retention / time.Second)
	if retention == 0 {
		retention = uint32(14 * 24 * time.Hour / time.Second)
	}
	row := map[string]any{
		"id":                meta.ID,
		"service_name":      meta.Service,
		"profile_type":      meta.Type,
		"started_at":        chTime(meta.StartedAt.UTC()),
		"bytes":             len(data),
		"path":              path,
		"ingested_at":       chTime(time.Now().UTC()),
		"retention_seconds": retention,
	}
	body, err := json.Marshal(row)
	if err != nil {
		return err
	}
	return c.insertRows(ctx, "profile_objects", append(body, '\n'))
}

// ListProfiles returns the most recent profiles.
func (c *ClickHouse) ListProfiles(ctx context.Context, limit int) ([]ProfileMeta, error) {
	if limit <= 0 || limit > 500 {
		limit = 100
	}
	sql := fmt.Sprintf(`SELECT id, service_name, profile_type, started_at, bytes, path, ingested_at
		FROM profile_objects FINAL ORDER BY started_at DESC LIMIT %d`, limit)
	rows, err := c.queryAggregate(ctx, sql, nil)
	if err != nil {
		return nil, err
	}
	var out []ProfileMeta
	for _, raw := range rows {
		var r struct {
			ID        string `json:"id"`
			Service   string `json:"service_name"`
			Type      string `json:"profile_type"`
			StartedAt string `json:"started_at"`
			Bytes     int64  `json:"bytes"`
			Path      string `json:"path"`
			Ingested  string `json:"ingested_at"`
		}
		if err := json.Unmarshal(raw, &r); err != nil {
			return nil, err
		}
		out = append(out, ProfileMeta{
			ID: r.ID, Service: r.Service, Type: r.Type,
			StartedAt: parseCHTime(r.StartedAt), Bytes: r.Bytes, Path: r.Path,
			IngestedAt: parseCHTime(r.Ingested),
		})
	}
	return out, nil
}

// GetProfile returns the metadata and the blob for one profile.
func (c *ClickHouse) GetProfile(ctx context.Context, id string) (ProfileMeta, []byte, error) {
	sql := `SELECT id, service_name, profile_type, started_at, bytes, path, ingested_at
		FROM profile_objects FINAL WHERE id = ? ORDER BY started_at DESC LIMIT 1`
	body, err := c.rawQueryParams(ctx, sql, []any{id})
	if err != nil {
		return ProfileMeta{}, nil, err
	}
	var r struct {
		ID        string `json:"id"`
		Service   string `json:"service_name"`
		Type      string `json:"profile_type"`
		StartedAt string `json:"started_at"`
		Bytes     int64  `json:"bytes"`
		Path      string `json:"path"`
		Ingested  string `json:"ingested_at"`
	}
	if err := json.Unmarshal([]byte(firstLine(body)), &r); err != nil {
		return ProfileMeta{}, nil, fmt.Errorf("profile %q not found", id)
	}
	meta := ProfileMeta{
		ID: r.ID, Service: r.Service, Type: r.Type,
		StartedAt: parseCHTime(r.StartedAt), Bytes: r.Bytes, Path: r.Path,
		IngestedAt: parseCHTime(r.Ingested),
	}
	// Only read what we wrote: the path comes from our own row, but resolve it
	// inside the profiles dir so a tampered row cannot read arbitrary files.
	if filepath.Dir(meta.Path) != filepath.Clean(ProfilesDir()) {
		return meta, nil, fmt.Errorf("profile path outside the profiles directory")
	}
	data, err := os.ReadFile(meta.Path)
	if err != nil {
		return meta, nil, fmt.Errorf("read profile: %w", err)
	}
	return meta, data, nil
}

func firstLine(b []byte) string {
	for i, c := range b {
		if c == '\n' {
			return string(b[:i])
		}
	}
	return string(b)
}
